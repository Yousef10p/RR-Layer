/* ============================================================================
   TEAM
   ----------------------------------------------------------------------------
   >>> DO NOT EDIT THIS FILE TO CHANGE TEAM MEMBERS. <<<
   Everyone's details live in ./team.json — a plain JSON file each member can
   fill in without touching any JavaScript. This module only reads that file,
   drops empty fields and hands the result to the UI.
   ============================================================================ */

import data from "./team.json";

/** Removes "" / null so the UI can simply test `if (member.linkedin)`. */
function clean(entry) {
  const out = {};
  Object.entries(entry).forEach(([key, value]) => {
    if (key.startsWith("_")) return;
    if (typeof value === "string" && value.trim() === "") return;
    if (value === null || value === undefined) return;
    out[key] = typeof value === "string" ? value.trim() : value;
  });
  return out;
}

export const team = (data.members ?? []).map(clean);
export const mentor = data.mentor ? clean(data.mentor) : null;
export const programme = data.programme ?? {};

/** How many links a card will actually render — used for the empty-state hint. */
export const hasLinks = (member) =>
  Boolean(member.linkedin || member.github || member.cv || member.email);

export default team;
